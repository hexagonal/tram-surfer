"""Generates src/palette.js and src/jptext.js for the game.

- The 64-colour palette is a median cut of the chosen-direction concept stills,
  plus the HUD and pickup colours so they never get muddied.
- Japanese text is pre-rendered to 1-bit bitmaps from the Unifont JP (16 px) and
  WenQuanYi Zen Hei Sharp (12 px) pixel fonts, so the game needs no web fonts.

Run from the repo root (needs numpy, pillow, fonts-unifont, fonts-wqy-zenhei):
    python3 tools/gen_assets.py
"""
import base64
import os
import sys

import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "concept"))
from render import jp_bitmap  # noqa: E402

KEEP = [  # HUD, pickups, characters and liveries that must stay exact
    "#ffd23a", "#c88a10", "#fffbe0", "#ffffff", "#140c1c", "#e8303c", "#ff8a3a", "#3fb8cc",
    "#e8953a", "#ffbe68", "#b8682a", "#fff0d8", "#2d6a3e", "#e8c050", "#7c1f28", "#d2a02a",
    "#6cb02c", "#ffbcd2", "#e27ea0", "#f2a41e", "#2a3264", "#f4cbaa", "#2f7ee6", "#c8ecff"]
SOURCES = ["f-swanston-direction", "g-stkilda-direction", "i-start-screen", "j-intro-storyboard",
           "h-dingo-designs"]

JP = {
    # (text, size, vertical)
    "swanston": ("スワンストン通り", 12, False),
    "title": ("トラムサーファー", 12, False),
    "surfer": ("サーファー", 16, False),
    "dingo": ("ディンゴ", 16, False),
    "gabu": ("ガブッ", 16, False),
    "hi": ("ひっ", 16, False),
    "gameover": ("ゲームオーバー", 12, False),
    "pause": ("ポーズ", 12, False),
    "ramen": ("ラーメン", 16, True),
    "sushi": ("寿司", 16, True),
    "izakaya": ("居酒屋", 16, True),
    "kissa": ("喫茶", 16, True),
    "karaoke": ("カラオケ", 16, True),
    "takoyaki": ("たこ焼き", 16, True),
    "noren_ramen": ("らーめん", 16, False),
    "noren_sushi": ("すし", 16, False),
}


def palette():
    px = []
    for name in SOURCES:
        a = np.asarray(Image.open(os.path.join(ROOT, "concept", "images", name + "-native.png")).convert("RGB"))
        px.append(a.reshape(-1, 3))
    a = np.concatenate(px)[None]
    im = Image.fromarray(a)
    mc = im.quantize(colors=160, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    flat = np.array(mc.getpalette()[:3 * 160], float).reshape(-1, 3)
    counts = np.bincount(np.asarray(mc).reshape(-1), minlength=160).astype(float)
    cols = [(c, w) for c, w in zip(flat, counts) if w > 0]
    keep = [np.array([int(k[i:i + 2], 16) for i in (1, 3, 5)], float) for k in KEEP]
    # fold colours that sit right next to a kept colour into it
    cols = [(c, w) for c, w in cols if min(np.linalg.norm(c - k) for k in keep) > 14]
    # merge the closest pair (weighted) until the palette fits: spreads the
    # colours out instead of spending a dozen on one sky gradient
    while len(cols) > 64 - len(KEEP):
        best = None
        for i in range(len(cols)):
            for j in range(i + 1, len(cols)):
                d = np.linalg.norm(cols[i][0] - cols[j][0])
                if best is None or d < best[0]:
                    best = (d, i, j)
        _, i, j = best
        (a, wa), (b, wb) = cols[i], cols[j]
        cols[i] = ((a * wa + b * wb) / (wa + wb), wa + wb)
        del cols[j]
    out = ["#%02x%02x%02x" % tuple(int(round(v)) for v in c) for c, _ in cols] + KEEP
    return sorted(set(out), key=out.index)


def bitmap(text, size, vertical):
    bm = jp_bitmap(text, size, vertical)
    ys, xs = np.nonzero(bm)
    bm = bm[: ys.max() + 1, : xs.max() + 1]  # trim right/bottom, keep top-left origin
    h, w = bm.shape
    bits = np.packbits(bm.reshape(-1)).tobytes()
    return w, h, base64.b64encode(bits).decode()


def main():
    cols = palette()
    with open(os.path.join(ROOT, "src", "palette.js"), "w") as f:
        f.write("// Generated by tools/gen_assets.py: 64 colours, no dither.\n")
        f.write("export const PALETTE = [\n")
        for i in range(0, 64, 8):
            f.write("  " + ", ".join(f"'{c}'" for c in cols[i:i + 8]) + ",\n")
        f.write("];\n")
    with open(os.path.join(ROOT, "src", "jptext.js"), "w") as f:
        f.write("// Generated by tools/gen_assets.py: 1-bit Japanese text bitmaps (row-major, MSB first).\n")
        f.write("// Japanese is decorative; English is always the primary text.\n")
        f.write("export const JP = {\n")
        for k, (t, s, v) in JP.items():
            w, h, b = bitmap(t, s, v)
            f.write(f"  {k}: {{ text: '{t}', w: {w}, h: {h}, bits: '{b}' }},\n")
        f.write("};\n")
    print("wrote palette.js and jptext.js")


if __name__ == "__main__":
    main()
